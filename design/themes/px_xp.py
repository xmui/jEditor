def grid(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 16, (len(rows))
    for r in rows: assert len(r) == 16, (r, len(r))
    return rows

def draw(name):
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(grid(I[name])):
        for x, ch in enumerate(row):
            c = P[ch]
            if c: im.putpixel((x, y), c + (255,))
    return im

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../app/themes/xp/tools')
os.makedirs(out, exist_ok=True)
for name in I:
    draw(name).save(os.path.join(out, name + '.png'), optimize=True)
if len(sys.argv) > 1:
    sheet = Image.new('RGBA', (len(I) * 20 * 6, 20 * 6), (220, 230, 246, 255))
    for i, name in enumerate(I):
        sheet.alpha_composite(draw(name).resize((96, 96), Image.NEAREST), (i * 120 + 12, 12))
    sheet.save(sys.argv[1])
